"""Generate the "3 extra tanks" companion's site header from the vanilla executable.

    python scripts/build_extra_tanks_headers.py "<vanilla Fish Tycoon folder>"

writes native/ftfp_extra_tanks/tank_sites.h. Every place "Extra Tanks.dll"
writes into the game is pinned here: each code site is disassembled from the
vanilla executable and must hold exactly the listed instruction, may begin at
a branch target but never contain one, and must not overlap a Fix Patcher
patch (data/fish_manifest.json). The two state vtable slots are pinned by the
function address each holds.

Two sites are shared on purpose with "DS Store Items.dll", which writes them
first: the tank screen's update call 0x421AAA and the state's Load slot
0x4424D0. The DLL chains them (it calls whatever the site called before it),
so it accepts either the stock bytes or a branch into another loaded module
(ftfp_extra_tanks.c, chain_ok). No other companion site is touched.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from build_ds_fish_headers import BASE, branch_targets, c_bytes, disasm, fix_patcher_ranges, load_exe, text  # noqa: E402

OUT = ROOT / "native" / "ftfp_extra_tanks" / "tank_sites.h"

# (name, va, expected instruction, what the DLL does there)
SITES = [
    ("tick_idle", 0x4218FF, "call 0x41fe70", "the tank screen's 5-minute fish update"),
    ("tick_show", 0x421AAA, "call 0x41fe70", "the fish update when the tank screen opens or switches tank"),
    ("release", 0x421D43, "call 0x421b20", "a held fish let go (a drop on a tank button)"),
    ("mouse", 0x421FFB, "call 0x421b80", "the tank screen's mouse handler (buttons and arrow)"),
    ("draw", 0x42208E, "jmp 0x4216e0", "the tank screen's button overlay"),
    ("save_quit", 0x41A663, "call 0x419100", "the save on quitting (a direct call of Save)"),
    ("new_game", 0x41AAC3, "call 0x41a8f0", "a new game's fish reset"),
    ("starter_eggs", 0x421646, "call 0x41fc90", "the starter eggs' 'no fish anywhere' test"),
    ("purchase", 0x427B30, "sub esp, 0x2b4", "the Supplies store's purchase (the Golden Seahorse's tank)"),
    ("background", 0x422013, "call 0x41d140", "the tank's background, chosen by tank number"),
    ("decor", 0x42203F, "call 0x41d340", "the tank's own decorations, chosen by tank number"),
    ("sale_shadow", 0x41D44A, "call 0x408a40", "the shadow under the Sale Tank's sign (sprite 3 at 580, 415)"),
    ("sale_sign", 0x41D467, "call 0x408a40", "the Sale Tank's For Sale sign (forsale.png, sprite 4, at 620, 360)"),
    ("sale_roll", 0x4246FB, "call 0x424240", "the sale scene's roll, once a second"),
    ("thoughts", 0x415131, "call 0x413530", "a customer's thought about a fish for sale"),
    ("crowd", 0x423F52, "call 0x413c10", "the sale scene's crowd, set when it opens"),
    ("pictures", 0x423FEE, "call 0x4234c0", "the sale scene's fish pictures, when it opens"),
    ("for_sale_text", 0x423927, "call 0x42b20b", "the Fish for sale number's sprintf"),
]
SHARED = {"tick_show"}             # DS Store Items chains this one too

# The state's vtable (0x44249C): slot address -> the function it holds.
VTABLE = [
    ("slot_load", 0x4424D0, 0x41AE70, "Load(slot)"),
    ("slot_save", 0x4424D4, 0x419100, "Save(slot)"),
]


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = load_exe(Path(sys.argv[1]))
    targets = branch_targets(data)
    patched = fix_patcher_ranges()
    lines = ["/* Generated by scripts/build_extra_tanks_headers.py from the vanilla Fish Tycoon.exe. */",
             "#ifndef FTFP_TANK_SITES_H", "#define FTFP_TANK_SITES_H", ""]
    for name, va, expected, purpose in SITES:
        ins = disasm(data, va, 1)[0]
        if text(ins) != expected:
            raise SystemExit(f"{name}: 0x{va:X} holds '{text(ins)}', expected '{expected}'")
        length = ins.size if ins.size >= 5 else 0
        if name == "purchase":
            length = 6
        if length < 5:
            raise SystemExit(f"{name}: too short")
        for t in targets:
            if va < t < va + length:
                raise SystemExit(f"{name}: a branch lands inside the site at 0x{t:X}")
        for start, end in patched:
            if start < va + length and va < end:
                raise SystemExit(f"{name}: overlaps a Fix Patcher patch at 0x{start:X}")
        raw = data[va - BASE: va - BASE + length]
        upper = name.upper()
        lines.append(f"/* {purpose}: {expected} */")
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_LEN {length}")
        lines.append(f"static const unsigned char SITE_{upper}_EXPECT[] = {{ {c_bytes(raw)} }};")
        if ins.mnemonic in ("call", "jmp"):
            lines.append(f"#define SITE_{upper}_TARGET 0x{int(ins.op_str, 16):08X}u")
        lines.append("")
    for name, va, holds, purpose in VTABLE:
        value = struct.unpack_from("<I", data, va - BASE)[0]
        if value != holds:
            raise SystemExit(f"{name}: 0x{va:X} holds 0x{value:X}, expected 0x{holds:X}")
        upper = name.upper()
        lines.append(f"/* the state's {purpose} */")
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_HOLDS 0x{holds:08X}u")
        lines.append("")
    lines.append(f"#define TANK_SITE_COUNT {len(SITES) + len(VTABLE)}")
    lines.append("")
    lines.append("#endif")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {len(SITES)} code sites, {len(VTABLE)} vtable slots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
