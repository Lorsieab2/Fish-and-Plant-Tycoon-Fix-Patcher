"""Build the tables "Unicode Text.dll" draws new letters with (both games).

    python scripts/build_unicode_drawing_tables.py ["<folder with Fish Tycoon and Plant Tycoon>"]

It writes
* native/ftfp_<game>_unicode/unicode_styles.h: each game font's STYLE, measured from the vanilla
  game's own font picture by src/text_maker.py (the same numbers the Text Maker draws its
  patcher-made letters with): its line height, capital top and baseline, the em (in pixels) at
  which Segoe UI's capital H is as tall as the font's own, the weight whose stem is nearest the
  font's own stem, the side bearings, the stroke of its missing-glyph box, and its alpha steps
  (a 256-entry table taking any coverage to the nearest alpha the font's own picture uses). The
  DLL draws every letter Windows makes for that font in that style (unicode_glyphs.h).
* native/common/unicode_compose_table.h: Unicode's canonical compositions (NFC: a base and one
  combining mark that make one precomposed letter, e.g. e + U+0301 = U+00E9), from Python's
  unicodedata, so a letter typed with a combining mark is drawn as its precomposed letter: the
  game font's own (or patcher-made) letter when it has it.

Run on Windows (the em and weight are measured with DirectWrite), after
scripts/build_unicode_assets.py, then rebuild the DLLs and run scripts/pin_unicode_text.py.
"""

from __future__ import annotations

from pathlib import Path
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

VANILLA = Path.home() / "Downloads" / "Current Modded LDW Games and Dumps" / "Vanilla Games"
GAME_FOLDERS = {"fish": "Fish Tycoon", "plant": "Plant Tycoon"}
STYLE_HEADERS = {"fish": ROOT / "native" / "ftfp_fish_unicode" / "unicode_styles.h",
                 "plant": ROOT / "native" / "ftfp_plant_unicode" / "unicode_styles.h"}
COMPOSE_HEADER = ROOT / "native" / "common" / "unicode_compose_table.h"
# the C name of each font's extended table in unicode_fonts.h (scripts/build_unicode_assets.py)
C_TABLES = {"paddington_tt_18": "table_paddington_18", "paddington_tt_30": "table_paddington_30",
            "font_triplex_sanslightlin_bold_16pt": "table_triplex_16", "PTfontsmall": "table_ptfontsmall"}


def font_style(font) -> dict:
    """A game font's style (src/text_maker.py unicode_style, as the Text Maker draws its letters)."""
    import text_maker as tm
    return tm.unicode_style(font)


def style_header(game: str, folder: Path) -> str:
    import text_maker as tm
    lines = [
        "/* Generated by scripts/build_unicode_drawing_tables.py from the vanilla game: do not edit.",
        "   Each game font's style (src/text_maker.py's metrics): the letters Windows draws for it are",
        "   drawn at its em, weight and baseline, with its side bearings and alpha steps",
        "   (unicode_glyphs.h). stock: the game's own table (Use Unicode Font leaves it); dll: the",
        "   extended table this DLL points the font at (Render Unicode with In-Game Fonts). */",
        "",
        "static const font_style FONT_STYLES[] = {",
    ]
    for font in tm.load_fonts(game, folder):
        if not font.in_game or font.spec.table is None:
            continue
        s = font_style(font)
        lines.append(f"    /* {font.key}: line {s['height']}, capital {s['cap_top']}..{s['baseline']} */")
        lines.append(f"    {{0x{font.spec.table:08X}u, {C_TABLES[font.key]}, {s['height']}, {s['cap_top']}, "
                     f"{s['baseline']}, {s['em']}, {s['weight']}, {s['left']}, {s['right']}, {s['stroke']},")
        levels = s["levels"]
        for row in range(0, 256, 32):
            lines.append("        " + ", ".join(str(v) for v in levels[row:row + 32]) + ",")
        lines.append("    },")
    lines.append("};")
    lines.append("#define FONT_STYLE_COUNT ((int)(sizeof FONT_STYLES / sizeof FONT_STYLES[0]))")
    return "\n".join(lines) + "\n"


def compositions() -> list[tuple[int, int, int]]:
    """(first, second, composite) for every canonical primary composite of two code points."""
    out = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        d = unicodedata.decomposition(chr(code))
        if not d or d.startswith("<"):
            continue
        parts = [int(p, 16) for p in d.split()]
        if len(parts) != 2:
            continue
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(code):
            continue                             # a composition exclusion
        out.append((parts[0], parts[1], code))
    out.sort()
    return out


def compose_header() -> str:
    pairs = compositions()
    lines = [
        "/* Generated by scripts/build_unicode_drawing_tables.py from Python's unicodedata "
        f"(Unicode {unicodedata.unidata_version}): do not edit.",
        "   Canonical compositions (NFC): {first, second, composite}, sorted by first then second. */",
        "#ifndef FTFP_UNICODE_COMPOSE_TABLE_H",
        "#define FTFP_UNICODE_COMPOSE_TABLE_H",
        "",
        f"#define COMPOSE_COUNT {len(pairs)}",
        "static const unsigned int COMPOSE[COMPOSE_COUNT][3] = {",
    ]
    row = []
    for a, b, c in pairs:
        row.append(f"{{0x{a:X}, 0x{b:X}, 0x{c:X}}}")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines += ["};", "", "#endif"]
    return "\n".join(lines) + "\n"


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else VANILLA
    COMPOSE_HEADER.write_text(compose_header(), encoding="utf-8", newline="\n")
    print(f"{COMPOSE_HEADER.relative_to(ROOT)}: {len(compositions())} compositions")
    for game, name in GAME_FOLDERS.items():
        STYLE_HEADERS[game].write_text(style_header(game, root / name), encoding="utf-8", newline="\n")
        print(f"{STYLE_HEADERS[game].relative_to(ROOT)} written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
