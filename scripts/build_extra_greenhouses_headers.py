"""Generate the Extra Greenhouses companion's site header from the vanilla Plant Tycoon.exe.

    python scripts/build_extra_greenhouses_headers.py "<vanilla Plant Tycoon folder>"

writes native/ftfp_extra_greenhouses/greenhouse_sites.h.

Thirteen code sites, pinned like scripts/build_new_flowers_headers.py pins its own
(stock instructions, no branch target inside, no overlap with a Fix Patcher
patch or a New Flowers, Plant Upgrades or Seed Boxes site), and the slots of
three scenes' vtables (greenhouse, nursery, snapshot), pinned by the stock
function each one holds.
"""

from __future__ import annotations

import importlib.util
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "native" / "ftfp_extra_greenhouses"
BASE = 0x400000


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


flower_headers = _load("build_new_flowers_headers")
upgrade_headers = _load("build_plant_upgrades_headers")
box_headers = _load("build_seed_boxes_headers")
disasm, text, c_bytes = flower_headers.disasm, flower_headers.text, flower_headers.c_bytes

# (name, address, the stock instructions the site replaces)
SITES = [
    # 0x41D810 updatePlants(state): the clock, then the plant manager's update of the 15 pots.
    ("plant_update", 0x41D810, ["push esi", "mov esi, ecx", "call 0x403430"]),
    # 0x41D120 save(slot), the game-save branch: write state + 8, 0x53FB0 bytes.
    ("save_write", 0x41D156, ["push edx", "lea eax, [ecx + 8]", "push 0x53fb0"]),
    # 0x41EE00 load(slot), after the body is copied in: the plant manager rebuilds its plants.
    ("load_done", 0x41EEFE, ["call 0x42fbc0", "mov ecx, eax", "call 0x42fc40"]),
    # 0x41D3D0 new game: the plant manager clears the 15 pots (0x42F630).
    ("new_game_clear", 0x41D3DC, ["call 0x42f630"]),
    # The slot menu's delete: 0x41D1F0(slot) removes the save file.
    ("delete_slot", 0x415F5E, ["call 0x41d1f0"]),
    # The greenhouse's pollen drop: 0x4240A0(target pot, donor pot = the selected pot).
    ("pollinate_call", 0x425F54, ["call 0x4240a0"]),
    # Seeds taken from a plant (held 0x14) read the selected pot's seed record (+0x54):
    # planted into a pot (0x425810), sent to the seed box (0x427960), trashed for their value
    # (+0x74, 0x424680), or put back (0x4244C0: 0x424480(selected) gives them back).
    ("seed_plant", 0x425C1B, ["lea esi, [edx + eax + 0x21dc]"]),
    ("seed_box", 0x42819B, ["lea esi, [edx + ecx + 0x21dc]"]),
    ("seed_trash", 0x424711, ["mov ebx, dword ptr [ecx + edi + 0x21fc]"]),
    ("seed_return", 0x424508, ["mov ebp, dword ptr [ecx + 0x63e58]"]),
    # The nursery tick's buy roll 0x436BE0(visitors browsing): run for every bought nursery.
    ("sales_roll", 0x437A1C, ["call 0x436be0"]),
    # A sale (0x435C70) hands the plant to a visitor when there is one (0x43ACD0, the visitor count).
    ("sale_visitor", 0x435D21, ["call 0x43acd0"]),
    # The greenhouse draw (0x428E70), after every pot and plant (0x423580 at 0x428FC0) and their
    # sparkles (0x423B00), just before what the hand holds (from here: a dragged pot, 0x4290C6; seeds,
    # pollen, a tool): the arrows go over the plants and under the hand.
    ("arrows_over_plants", 0x429066, ["mov ecx, dword ptr [esi + 0x88]"]),
]

# (name, slot address, stock function): the vtables at 0x469220 (greenhouse),
# 0x469730 (nursery) and 0x469888 (snapshot, F1 in the greenhouse).
VTABLE = [
    ("gh_mouse", 0x469224, 0x4273D0),
    ("gh_key", 0x469228, 0x4232F0),
    ("gh_command", 0x46922C, 0x427960),
    ("gh_overlay", 0x469238, 0x4257A0),
    ("gh_draw", 0x46923C, 0x428E70),
    ("gh_tick", 0x469240, 0x428810),
    ("gh_activate", 0x469244, 0x4231E0),
    ("nu_mouse", 0x469734, 0x4363E0),
    ("nu_key", 0x469738, 0x435070),
    ("nu_command", 0x46973C, 0x4351C0),
    ("nu_draw", 0x469748, 0x437BF0),
    ("nu_overlay", 0x46974C, 0x416730),
    ("nu_tick", 0x469750, 0x437950),
    ("nu_activate", 0x469754, 0x4360D0),
    ("sn_mouse", 0x46988C, 0x448D20),
    ("sn_key", 0x469890, 0x448A30),
    ("sn_command", 0x469894, 0x448A60),
    ("sn_draw", 0x4698A0, 0x448BF0),
    ("sn_activate", 0x4698AC, 0x448EB0),
]


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = (Path(sys.argv[1]) / "Plant Tycoon.exe").read_bytes()
    taken = flower_headers.fix_patcher_ranges()
    targets = flower_headers.branch_targets(data)
    used = []
    for module in (flower_headers, upgrade_headers, box_headers):
        for name, va, expect in module.SITES:
            used.append((va, va + sum(len(i.bytes) for i in disasm(data, va, len(expect))), name))
    for name, va, _function in box_headers.VTABLE:
        used.append((va, va + 4, name))
    lines = ["/* Generated by scripts/build_extra_greenhouses_headers.py from the vanilla Plant Tycoon.exe. Do not edit. */",
             "#ifndef FTFP_GREENHOUSE_SITES_H", "#define FTFP_GREENHOUSE_SITES_H", ""]

    def emit(name: str, va: int, raw: bytes) -> None:
        upper = name.upper()
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_LEN {len(raw)}")
        lines.append(f"static const unsigned char SITE_{upper}_EXPECT[] = {{ {c_bytes(raw)} }};")

    for name, va, expect in SITES:
        got = disasm(data, va, len(expect))
        if [text(i) for i in got] != expect:
            raise SystemExit(f"{name} at 0x{va:X}: expected {expect}, found {[text(i) for i in got]}")
        raw = b"".join(bytes(i.bytes) for i in got)
        end = va + len(raw)
        if len(raw) < 5:
            raise SystemExit(f"{name} at 0x{va:X} is {len(raw)} bytes; a jump needs 5")
        for start, stop in taken:
            if va < stop and start < end:
                raise SystemExit(f"{name} at 0x{va:X} overlaps a Fix Patcher patch at 0x{start:X}")
        for start, stop, other in used:
            if va < stop and start < end:
                raise SystemExit(f"{name} at 0x{va:X} overlaps {other}")
        inside = sorted(t for t in targets if va < t < end)
        if inside:
            raise SystemExit(f"{name} at 0x{va:X} contains branch target(s) {[hex(t) for t in inside]}")
        emit(name, va, raw)
        lines.append(f"#define SITE_{name.upper()}_BACK 0x{end:08X}u")

    for name, va, function in VTABLE:
        stock = data[va - BASE: va - BASE + 4]
        if struct.unpack("<I", stock)[0] != function:
            raise SystemExit(f"{name}: the vtable slot at 0x{va:X} does not hold 0x{function:X}")
        for start, stop, other in used:
            if va < stop and start < va + 4:
                raise SystemExit(f"{name} at 0x{va:X} overlaps {other}")
        lines.append(f"#define SLOT_{name.upper()}_VA 0x{va:08X}u")
        lines.append(f"#define SLOT_{name.upper()}_STOCK 0x{function:08X}u")

    lines += ["", "#endif", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "greenhouse_sites.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"greenhouse_sites.h: {len(SITES)} code sites, {len(VTABLE)} vtable slots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
