"""Generate the Multiple Ornaments companion's site header from the vanilla executable.

    python scripts/build_ornaments_headers.py "<vanilla Fish Tycoon folder>"

writes native/ftfp_ornaments/orn_sites.h. Every place "Multiple Ornaments.dll"
writes into the game is disassembled from the vanilla executable and must hold
exactly the listed instructions, may begin at a branch target but never
contain one, and must not overlap a Fix Patcher patch (data/fish_manifest.json),
a DS Fish site (native/ftfp_ds_fish/ds_sites.h) or a DS Store Items site
(native/ftfp_ds_store/store_sites.h).

Most sites are calls the DLL redirects to a stub that calls the same stock
function and then does the same for the decorative copies, so they compose
with the DS Store Items hooks inside those functions (the ornament pick at
0x41E570 and the ornament pass at 0x41EF1B are hooked at their entries there,
never at these call sites).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from build_ds_fish_headers import branch_targets, c_bytes, disasm, fix_patcher_ranges, load_exe, text  # noqa: E402
from build_ds_store_headers import ds_fish_ranges  # noqa: E402

OUT = ROOT / "native" / "ftfp_ornaments"

# (name, va, expected instructions)
SITES = [
    # The tank scene's draw (0x422010) calls the decor pass, which ends with the ornaments.
    ("draw_decor", 0x422062, ["call 0x41ee60"]),
    # The tank scene's update (0x4220A0) calls the ornament fall (0x41DB00) every frame.
    ("ornament_fall", 0x4220D8, ["call 0x41db00"]),
    # The press in a tank (0x41EFB0): fish, then the snail and plants, then the ornament pick.
    ("ornament_pick", 0x41EFD9, ["call 0x41e570"]),
    # The mouse moving while something is dragged (0x421B80): the drag of a held ornament.
    ("drag_move", 0x421BA0, ["call 0x41e600"]),
    # The release after a drag (0x421CFC path): the fish drop, the tool use or the ornament drop.
    ("drag_drop", 0x421D43, ["call 0x421b20"]),
    # A new game clears every tank's ornaments (0x4194A0) from the game's reset (0x41AA60).
    ("new_game", 0x41AA98, ["call 0x4194a0"]),
    # The state's Save(slot) on a game slot (not 0 or 11): before the state is written.
    ("save", 0x419160, ["push edx", "lea eax, [ecx + 8]", "push 0x1e3c8"]),
    # The state's Load(slot) on a game slot, once the file has been read: before the copy. It starts
    # after 0x41AF54, which Fix Vanilla Bugs routes through its full-meters routine (back to 0x41AF59).
    ("load", 0x41AF59, ["lea ecx, [esp + 0x120]"]),
    # The store's Buy click (0x4282A0): an owned permanent item is refused here.
    ("store_click", 0x4282C6, ["lea edi, [eax + eax*4 + 0x1e]", "cmp dword ptr [edx + edi*4], esi"]),
    # The store panel (0x427240): an owned permanent item shows "This is in your inventory."
    ("store_panel", 0x427351, ["lea edx, [eax + eax*4 + 0x1e]", "mov eax, dword ptr [esi + 0x10]"]),
]


def ds_store_ranges() -> list[tuple[int, int, str]]:
    header = (ROOT / "native" / "ftfp_ds_store" / "store_sites.h").read_text(encoding="utf-8")
    vas = dict(re.findall(r"#define SITE_(\w+)_VA (0x[0-9A-F]+)u", header))
    lens = dict(re.findall(r"#define SITE_(\w+)_LEN (\d+)", header))
    return [(int(vas[k], 16), int(vas[k], 16) + int(lens[k]), f"DS Store {k}") for k in vas]


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = load_exe(Path(sys.argv[1]))
    taken = ([(s, e, "a Fix Patcher patch") for s, e in fix_patcher_ranges()]
             + ds_fish_ranges() + ds_store_ranges())
    targets = branch_targets(data)
    used: list[tuple[int, int, str]] = []
    lines = ["/* Generated by scripts/build_ornaments_headers.py from the vanilla Fish Tycoon.exe. Do not edit. */",
             "#ifndef FTFP_ORN_SITES_H", "#define FTFP_ORN_SITES_H", ""]
    for name, va, expect in SITES:
        got = disasm(data, va, len(expect))
        if [text(i) for i in got] != expect:
            raise SystemExit(f"{name} at 0x{va:X}: expected {expect}, found {[text(i) for i in got]}")
        raw = b"".join(bytes(i.bytes) for i in got)
        if len(raw) < 5:
            raise SystemExit(f"{name} at 0x{va:X} is {len(raw)} bytes; a jump needs 5")
        for start, end, other in taken + used:
            if va < end and start < va + len(raw):
                raise SystemExit(f"{name} at 0x{va:X} overlaps {other} at 0x{start:X}")
        inside = sorted(t for t in targets if va < t < va + len(raw))
        if inside:
            raise SystemExit(f"{name} at 0x{va:X} contains branch target(s) {[hex(t) for t in inside]}")
        used.append((va, va + len(raw), name))
        upper = name.upper()
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_LEN {len(raw)}")
        lines.append(f"static const unsigned char SITE_{upper}_EXPECT[] = {{ {c_bytes(raw)} }};")
    lines.append("")
    lines.append(f"#define ORN_SITE_COUNT {len(SITES)}")
    lines += ["", "#endif", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "orn_sites.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"orn_sites.h: {len(SITES)} code sites")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
