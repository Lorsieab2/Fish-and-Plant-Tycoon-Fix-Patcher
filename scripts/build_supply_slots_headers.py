"""Generate the "Extra supply slots" companion's site header from the vanilla executable.

    python scripts/build_supply_slots_headers.py "<vanilla Fish Tycoon folder>"

writes native/ftfp_supply_slots/slot_sites.h. Every place "Extra Supply Slots.dll"
writes into the game is pinned here: each code site is disassembled from the
vanilla executable and must hold exactly the listed instruction, may begin at
a branch target but never contain one, and must not overlap a Fix Patcher
patch (data/fish_manifest.json). The two state vtable slots are pinned by the
function address each holds.

Six sites are shared on purpose with other companions, which may write them
first: the tank screen's mouse call, its release call and its overlay jump
(Extra Tanks, and Multiple Ornaments' release), the save on quitting (Extra
Tanks and DS Store Items), a new game's fish reset (Extra Tanks) and the
state's Load/Save slots (Extra Tanks, DS Store Items, Multiple Ornaments). The
DLL chains each of them: it accepts the stock bytes or the same kind of branch
into another loaded module, and calls whatever was there before
(ftfp_supply_slots.c, branch_site / slot_site). The other three sites (the
two calls that draw the supply slots' pictures and the store's Buy call) are
touched by no other companion and by no Fix Patcher patch
(tests/test_supply_slots.py checks every DLL's site list and the manifest).
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from build_ds_fish_headers import BASE, branch_targets, c_bytes, disasm, fix_patcher_ranges, load_exe, text  # noqa: E402

OUT = ROOT / "native" / "ftfp_supply_slots" / "slot_sites.h"

# (name, va, expected instruction, what the DLL does there)
SITES = [
    ("mouse", 0x421FFB, "call 0x421b80", "the tank screen's mouse handler: the slot arrows and the extra slots"),
    ("release", 0x421D43, "call 0x421b20", "a held supply let go: a drop on a supply slot"),
    ("draw", 0x42208E, "jmp 0x4216e0", "the tank screen's overlay: the slot arrows and the refusal"),
    ("tank_slots", 0x41EF3A, "call 0x41beb0", "the tank screen's supply slot pictures"),
    ("store_slots", 0x4279F2, "call 0x41beb0", "the Supplies store's supply slot pictures"),
    ("store_buy", 0x4282DA, "call 0x428080", "the Supplies store's Buy of a stock item"),
    ("save_quit", 0x41A663, "call 0x419100", "the save on quitting (a direct call of Save)"),
    ("new_game", 0x41AAC3, "call 0x41a8f0", "a new game's fish reset"),
]
SHARED = {"mouse", "release", "draw", "save_quit", "new_game"}

# The state's vtable (0x44249C): slot address -> the function it holds.
VTABLE = [
    ("slot_load", 0x4424D0, 0x41AE70, "Load(slot)"),
    ("slot_save", 0x4424D4, 0x419100, "Save(slot)"),
]


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = load_exe(Path(sys.argv[1]))
    targets = branch_targets(data)
    patched = fix_patcher_ranges()
    lines = ["/* Generated by scripts/build_supply_slots_headers.py from the vanilla Fish Tycoon.exe. */",
             "#ifndef FTFP_SLOT_SITES_H", "#define FTFP_SLOT_SITES_H", ""]
    for name, va, expected, purpose in SITES:
        ins = disasm(data, va, 1)[0]
        if text(ins) != expected:
            raise SystemExit(f"{name}: 0x{va:X} holds '{text(ins)}', expected '{expected}'")
        length = ins.size
        if length < 5:
            raise SystemExit(f"{name}: too short")
        for t in targets:
            if va < t < va + length:
                raise SystemExit(f"{name}: a branch lands inside the site at 0x{t:X}")
        for start, end in patched:
            if start < va + length and va < end:
                raise SystemExit(f"{name}: overlaps a Fix Patcher patch at 0x{start:X}")
        raw = data[va - BASE: va - BASE + length]
        upper = name.upper()
        lines.append(f"/* {purpose}: {expected} */")
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_LEN {length}")
        lines.append(f"static const unsigned char SITE_{upper}_EXPECT[] = {{ {c_bytes(raw)} }};")
        lines.append(f"#define SITE_{upper}_TARGET 0x{int(ins.op_str, 16):08X}u")
        lines.append("")
    for name, va, holds, purpose in VTABLE:
        value = struct.unpack_from("<I", data, va - BASE)[0]
        if value != holds:
            raise SystemExit(f"{name}: 0x{va:X} holds 0x{value:X}, expected 0x{holds:X}")
        upper = name.upper()
        lines.append(f"/* the state's {purpose} */")
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_HOLDS 0x{holds:08X}u")
        lines.append("")
    lines.append(f"#define SLOT_SITE_COUNT {len(SITES) + len(VTABLE)}")
    lines.append("")
    lines.append("#endif")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {len(SITES)} code sites, {len(VTABLE)} vtable slots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
