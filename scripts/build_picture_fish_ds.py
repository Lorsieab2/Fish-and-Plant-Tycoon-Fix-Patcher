"""Writes src/pictures_fish_ds.py: the DS Exclusive Fish companion's drawing data (the pair
fin anchors and the head-on extents its DLL draws with, native/ftfp_ds_fish/ds_data.h),
taken from data/ds_fish_layout.json, the file ds_data.h is built from. Picture Studio ships
the Python module, not the JSON. tests/test_pictures_fish.py checks the module is current."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = ROOT / "data" / "ds_fish_layout.json"
TARGET = ROOT / "src" / "pictures_fish_ds.py"


def render() -> str:
    layout = json.loads(LAYOUT.read_text(encoding="utf-8"))
    anchors = {(p["body"], p["fin"]): tuple(p["anchor"]) for p in layout["pair_anchors"]}
    extents = {int(g): {part: tuple(tuple(v) for v in e[part]) for part in ("body", "top", "bot")}
               for g, e in layout["head_on"]["extents"].items()}
    lines = [
        '"""DS Exclusive Fish\'s drawing data, generated by scripts/build_picture_fish_ds.py from',
        "data/ds_fish_layout.json (the source of native/ftfp_ds_fish/ds_data.h). Do not edit.",
        "",
        "PAIR_ANCHOR: (body, fin) -> (top x, top y, bottom x, bottom y), for every pair with a DS gene",
        "(the DLL's pair_anchors). EXTENT: gene -> part -> the (left, right) of the drawn pixels in",
        'frames 0, 12, 13, 14, 15, 16 and 17 (the DLL\'s head_on_x)."""',
        "",
        "PAIR_ANCHOR = {",
    ]
    for key in sorted(anchors):
        lines.append(f"    {key}: {anchors[key]},")
    lines.append("}")
    lines.append("")
    lines.append("EXTENT = {")
    for gene in sorted(extents):
        lines.append(f"    {gene}: {{")
        for part in ("body", "top", "bot"):
            lines.append(f"        {part!r}: {extents[gene][part]},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
