"""Generate the Extra Chemical Slots companion's site header from the vanilla Plant Tycoon.exe.

    python scripts/build_chem_slots_headers.py "<vanilla Plant Tycoon folder>"

writes native/ftfp_chem_slots/chem_slots_sites.h.

Five calls of the greenhouse screen and the heads of two of the chemical tray's
functions, pinned like scripts/build_new_flowers_headers.py pins its own (stock
instructions, no branch target inside, no overlap with a Fix Patcher patch or a
site of New Flowers, Plant Upgrades, the Seed Boxes, Extra Greenhouses or
Greenhouse Counts), and two slots of the greenhouse screen's table, pinned by
the stock function each one holds (the DLL chains the wrappers other companions
put there).
"""

from __future__ import annotations

import importlib.util
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "native" / "ftfp_chem_slots"
BASE = 0x400000


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


flower_headers = _load("build_new_flowers_headers")
upgrade_headers = _load("build_plant_upgrades_headers")
box_headers = _load("build_seed_boxes_headers")
greenhouse_headers = _load("build_extra_greenhouses_headers")
disasm, text, c_bytes = flower_headers.disasm, flower_headers.text, flower_headers.c_bytes

# Greenhouse Counts' one code site (native/ftfp_greenhouse_counts: HELD_SITE_VA .. HELD_SITE_BACK).
COUNTS_SITES = [("counts_held", 0x4291D2, 0x4291DB)]

# (name, address, the stock instructions the site replaces)
SITES = [
    # The greenhouse press (0x426040): the tools' hit test (0x423AA0, thiscall scene (x, y)) ...
    ("tool_hit", 0x42606E, ["call 0x423aa0"]),
    # ... and the chemical tray's (0x4165A0, thiscall tray (x, y)): -1, or the slot to pick up / put back on.
    ("tray_hit", 0x4260A9, ["call 0x4165a0"]),
    # The greenhouse mouse move, the hand empty: the tray slot under the mouse (0x416600) for its tooltip.
    ("tray_spot", 0x427765, ["call 0x416600"]),
    # The greenhouse draw (0x428E70): the four tools (0x44DD70) and the tray (0x416650).
    ("tools_draw", 0x428EE2, ["call 0x44dd70"]),
    ("tray_draw", 0x428EFC, ["call 0x416650"]),
    # The tray's add(id, doses) and room(id): the store's Buy (0x432E55) and its room check (0x432727).
    ("tray_add", 0x416410, ["push esi", "mov esi, dword ptr [ecx]", "push edi", "mov edi, dword ptr [esp + 0xc]"]),
    ("tray_room", 0x4164B0, ["mov ecx, dword ptr [ecx]", "push esi", "mov esi, dword ptr [esp + 8]"]),
]

# (name, slot address, stock function): the greenhouse screen's table at 0x469220.
VTABLE = [
    ("gh_mouse", 0x469224, 0x4273D0),
    ("gh_activate", 0x469244, 0x4231E0),
]


def used_ranges(data: bytes) -> list[tuple[int, int, str]]:
    used = []
    for module in (flower_headers, upgrade_headers, box_headers, greenhouse_headers):
        for name, va, expect in module.SITES:
            used.append((va, va + sum(len(i.bytes) for i in disasm(data, va, len(expect))), name))
    for name, va, _function in box_headers.VTABLE:
        used.append((va, va + 4, name))
    for name, start, stop in COUNTS_SITES:
        used.append((start, stop, name))
    return used


def main() -> int:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = (Path(sys.argv[1]) / "Plant Tycoon.exe").read_bytes()
    taken = flower_headers.fix_patcher_ranges()
    targets = flower_headers.branch_targets(data)
    used = used_ranges(data)
    lines = ["/* Generated by scripts/build_chem_slots_headers.py from the vanilla Plant Tycoon.exe. Do not edit. */",
             "#ifndef FTFP_CHEM_SLOTS_SITES_H", "#define FTFP_CHEM_SLOTS_SITES_H", ""]

    for name, va, expect in SITES:
        got = disasm(data, va, len(expect))
        if [text(i) for i in got] != expect:
            raise SystemExit(f"{name} at 0x{va:X}: expected {expect}, found {[text(i) for i in got]}")
        raw = b"".join(bytes(i.bytes) for i in got)
        end = va + len(raw)
        if len(raw) < 5:
            raise SystemExit(f"{name} at 0x{va:X} is {len(raw)} bytes; a jump needs 5")
        for start, stop in taken:
            if va < stop and start < end:
                raise SystemExit(f"{name} at 0x{va:X} overlaps a Fix Patcher patch at 0x{start:X}")
        for start, stop, other in used:
            if va < stop and start < end:
                raise SystemExit(f"{name} at 0x{va:X} overlaps {other}")
        inside = sorted(t for t in targets if va < t < end)
        if inside:
            raise SystemExit(f"{name} at 0x{va:X} contains branch target(s) {[hex(t) for t in inside]}")
        upper = name.upper()
        lines.append(f"#define SITE_{upper}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{upper}_LEN {len(raw)}")
        lines.append(f"static const unsigned char SITE_{upper}_EXPECT[] = {{ {c_bytes(raw)} }};")
        lines.append(f"#define SITE_{upper}_BACK 0x{end:08X}u")

    for name, va, function in VTABLE:
        stock = data[va - BASE: va - BASE + 4]
        if struct.unpack("<I", stock)[0] != function:
            raise SystemExit(f"{name}: the vtable slot at 0x{va:X} does not hold 0x{function:X}")
        lines.append(f"#define SITE_{name.upper()}_VA 0x{va:08X}u")
        lines.append(f"#define SITE_{name.upper()}_STOCK 0x{function:08X}u")

    lines += ["", "#endif", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "chem_slots_sites.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"chem_slots_sites.h: {len(SITES)} code sites, {len(VTABLE)} table slots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
